// Rust types → TypeScript. ts-rs writes one file per `#[ts(export)]` type into ui/src/shared/generated when its export
// tests run (where and how: .cargo/config.toml). Old files go first, so a removed or renamed type leaves nothing behind;
// index.ts then re-exports them all. Run by `pnpm check` before the type check; CI fails when the result differs from
// what is committed (docs/architecture.md).
import { execFileSync } from 'node:child_process'
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'ui', 'src', 'shared', 'generated')

rmSync(out, { recursive: true, force: true })
mkdirSync(out, { recursive: true })
execFileSync('cargo', ['test', '--workspace', '--lib', '--quiet', 'export_bindings'], { cwd: root, stdio: 'inherit' })

const names = readdirSync(out)
  .filter((f) => f.endsWith('.ts'))
  .map((f) => f.slice(0, -3))
  .sort()
if (!names.length) throw new Error('ts-rs wrote no types')
const index = ['// Generated by scripts/types.mjs from the Rust types. Do not edit this file manually.', ...names.map((n) => `export type { ${n} } from './${n}'`), ''].join('\n')
writeFileSync(join(out, 'index.ts'), index)
console.log(`${names.length} types in ui/src/shared/generated`)
