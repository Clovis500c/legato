// Rust types → TypeScript. ts-rs writes one file per `#[ts(export)]` type into a temporary folder when its export tests
// run (TS_RS_EXPORT_DIR overrides .cargo/config.toml, which points at ui/src/shared/generated). Only when cargo has
// succeeded do the old files go and the new ones come in, so a removed or renamed type leaves nothing behind and a Rust
// compile error leaves the committed files alone; index.ts then re-exports them all. Run by `pnpm check` before the type
// check; CI fails when the result differs from what is committed (docs/architecture.md).
import { execFileSync } from 'node:child_process'
import { cpSync, mkdirSync, mkdtempSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'ui', 'src', 'shared', 'generated')
const tmp = mkdtempSync(join(tmpdir(), 'legato-types-'))

try {
  execFileSync('cargo', ['test', '--workspace', '--lib', '--quiet', 'export_bindings'], { cwd: root, stdio: 'inherit', env: { ...process.env, TS_RS_EXPORT_DIR: tmp } })

  const names = readdirSync(tmp)
    .filter((f) => f.endsWith('.ts'))
    .map((f) => f.slice(0, -3))
    .sort()
  if (!names.length) throw new Error('ts-rs wrote no types')
  const index = ['// Generated by scripts/types.mjs from the Rust types. Do not edit this file manually.', ...names.map((n) => `export type { ${n} } from './${n}'`), ''].join('\n')
  writeFileSync(join(tmp, 'index.ts'), index)

  rmSync(out, { recursive: true, force: true })
  mkdirSync(out, { recursive: true })
  cpSync(tmp, out, { recursive: true })
  console.log(`${names.length} types in ui/src/shared/generated`)
} finally {
  rmSync(tmp, { recursive: true, force: true })
}
